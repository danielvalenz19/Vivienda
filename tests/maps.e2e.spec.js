'use strict';
const {test,expect}=require('@playwright/test');
const {fixture}=require('./fixture-server');
const {DatabaseSync}=require('node:sqlite');
let site;
test.beforeAll(async()=>{site=await fixture();const db=new DatabaseSync(site.dbPath);db.prepare("INSERT INTO listings(owner,title,city,area,type,price,deposit,description,rooms,baths,status,authorization,confirmed) VALUES(?,'DEMO capital','Ciudad de Guatemala','Zona 4','Cuarto',1200,1000,'Dato ficticio de demostración',1,1,'active','approved',CURRENT_TIMESTAMP)").run(site.owner);db.close()});
test.afterAll(async()=>{if(site)await site.close()});
test('mapas muestran referencias de ciudad, preservan filtros y no inventan ubicación',async({page})=>{
  await page.route('https://tile.openstreetmap.org/**',route=>route.abort());
  await page.setViewportSize({width:390,height:844});
  await page.goto(site.url);
  await expect(page.getByRole('heading',{name:'Viviendas disponibles'})).toBeVisible();
  await page.getByRole('button',{name:'Ver mapa de ciudades'}).click();
  await expect(page.getByRole('region',{name:'Mapa interactivo orientativo'})).toBeVisible();
  await expect(page.getByText(/El mapa muestra la ciudad como referencia/)).toBeVisible();
  await expect(page.getByRole('list',{name:'Resumen de resultados por ciudad'})).toContainText('Quetzaltenango (Xela) · 1 vivienda');
  await expect(page.getByRole('list',{name:'Resumen de resultados por ciudad'})).toContainText('Ciudad de Guatemala · 1 vivienda');
  await expect(page.locator('.vgt-map .leaflet-marker-icon')).toHaveCount(2);
  await expect(page.locator('.vgt-map .leaflet-control-attribution')).toContainText('OpenStreetMap');
  await expect(page.getByText(/No se pudo cargar el fondo del mapa/)).toBeVisible({timeout:10000});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.getByRole('button',{name:'Ocultar mapa'}).click();
  await page.getByRole('button',{name:'Ver mapa de ciudades'}).click();
  await expect(page.getByRole('list',{name:'Resumen de resultados por ciudad'}).locator('li')).toHaveCount(2);
  await page.getByRole('button',{name:'Ocultar mapa'}).click();
  await page.getByRole('button',{name:'Ubicación',exact:true}).click();
  await page.getByRole('option',{name:'Quetzaltenango',exact:true}).click();
  await page.getByRole('button',{name:'Buscar',exact:true}).click();
  await page.getByRole('button',{name:'Ver mapa de ciudades'}).click();
  await expect(page.getByRole('list',{name:'Resumen de resultados por ciudad'}).locator('li')).toHaveCount(1);
  await expect(page.getByRole('list',{name:'Resumen de resultados por ciudad'})).toContainText('Quetzaltenango (Xela) · 1 vivienda');
  await page.getByRole('link',{name:'DEMO prueba de navegador',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Ubicación de referencia'})).toBeVisible();
  await expect(page.getByText(/Todavía no contamos con datos geográficos confiables/)).toBeVisible();
  await expect(page.locator('.detail-section .vgt-map .leaflet-marker-icon')).toHaveCount(0);
});
